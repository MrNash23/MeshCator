#!/usr/bin/env python3
"""Generate simplified admin polygons/labels from Natural Earth Public Domain data."""
import json, math, hashlib, unicodedata
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
FILES=['ne_50m_admin_0_countries.geojson','ne_10m_admin_1_states_provinces.geojson']
REGIONS={'Germany','France','Belgium','Netherlands','Luxembourg','Denmark','Poland','Czechia','Czech Republic','Austria','Switzerland'}
def simplify(p,e):
 if len(p)<3:return p
 a,b=p[0],p[-1];dx=b[0]-a[0];dy=b[1]-a[1];den=dx*dx+dy*dy
 best=-1;idx=0
 for i,c in enumerate(p[1:-1],1):
  t=max(0,min(1,((c[0]-a[0])*dx+(c[1]-a[1])*dy)/den)) if den else 0
  d=(c[0]-a[0]-t*dx)**2+(c[1]-a[1]-t*dy)**2
  if d>best:best=d;idx=i
 if best>e*e:return simplify(p[:idx+1],e)[:-1]+simplify(p[idx:],e)
 return [a,b]
def text(s):
 # Existing embedded font supports Latin-1. Transliterate other characters.
 out=''
 for c in s or '':
  out+=c if 32<=ord(c)<=255 else ''.join(x for x in unicodedata.normalize('NFKD',c) if 32<=ord(x)<127)
 return out.replace('’',"'")
points=[];rings=[];areas=[]
for level,file in enumerate(FILES):
 features=json.loads((ROOT/'assets/maps'/file).read_text())['features']
 for f in features:
  p=f['properties'];g=f['geometry']
  if level and p.get('admin') not in REGIONS:continue
  name=p.get('NAME_EN' if not level else 'name_en') or p.get('NAME' if not level else 'name')
  if not name:continue
  polys=g['coordinates'] if g['type']=='MultiPolygon' else [g['coordinates']]
  first=len(rings)
  for poly in polys:
   for ring in poly:
    epsilon=0.25 if not level else 0.045
    if ring is polys[0][0]:epsilon=min(epsilon,(max(a[0] for a in ring)-min(a[0] for a in ring))/8,(max(a[1] for a in ring)-min(a[1] for a in ring))/8)
    q=simplify(ring,epsilon)
    q=[(round(a*100),round(b*100)) for a,b,*_ in q]
    if len(set(q))<3:continue
    rings.append((len(points),len(q)));points.extend(q)
  if len(rings)==first:continue
  names=[text(p.get(('NAME_' if not level else 'name_')+lang) or name) for lang in (['EN','FR','ES','DE'] if not level else ['en','fr','es','de'])]
  lon=p.get('LABEL_X' if not level else 'longitude');lat=p.get('LABEL_Y' if not level else 'latitude')
  if lon is None or lat is None:continue
  areas.append((first,len(rings)-first,round(lon*100),round(lat*100),level,names))
s='// Generated by tools/build_admin_map.py; Natural Earth Public Domain.\n#pragma once\n#include <cstdint>\nnamespace mc {\nstruct AdminPoint {int16_t lon,lat;};\nstruct AdminRing {uint32_t first;uint16_t count;};\nstruct AdminArea {uint16_t first,count;int16_t lon,lat;uint8_t level;const char* names[4];};\ninline constexpr AdminPoint adminPoints[]={\n'
s+=''.join('{%d,%d},'%p for p in points)+'\n};\ninline constexpr AdminRing adminRings[]={\n'+''.join('{%d,%d},'%r for r in rings)+'\n};\ninline constexpr AdminArea adminAreas[]={\n'
for a,b,c,d,e,names in areas:s+='{%d,%d,%d,%d,%d,{'%(a,b,c,d,e)+','.join(json.dumps(n,ensure_ascii=False) for n in names)+'}},\n'
s+='};\n}\n';(ROOT/'src/maps/AdminData.h').write_text(s)
manifest={'license':'Public Domain','terms':'https://www.naturalearthdata.com/about/terms-of-use/','country_count':sum(a[4]==0 for a in areas),'region_count':sum(a[4]==1 for a in areas),'regional_coverage':sorted(REGIONS),'precision_degrees':0.01,'simplification_degrees':{'country':0.25,'region':0.045},'point_count':len(points),'sources':{f:{'url':'https://github.com/nvkelso/natural-earth-vector/blob/master/geojson/'+f,'sha256':hashlib.sha256((ROOT/'assets/maps'/f).read_bytes()).hexdigest()} for f in FILES}}
(ROOT/'assets/maps/admin-manifest.json').write_text(json.dumps(manifest,indent=2)+'\n');print(manifest['country_count'],manifest['region_count'],'areas;',len(points),'points;',len(rings),'rings')
