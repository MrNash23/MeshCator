"""Reproducible Natural Earth 110m coastline -> quantized C++ geometry."""
import json, hashlib
from pathlib import Path
source=Path('assets/maps/ne_110m_coastline.geojson')
j=json.loads(source.read_text()); points=[]; spans=[]
for f in j['features']:
 line=f['geometry']['coordinates']; start=len(points)
 for lon,lat,*_ in line:
  pt=(round(lon*100),round(lat*100))
  if len(points)==start or points[-1]!=pt:points.append(pt)
 spans.append((start,len(points)-start))
out='// Natural Earth 110m coastline, public domain. Generated by tools/build_world.py.\n#pragma once\n#include <cstdint>\nnamespace mc {\nstruct CoastPoint { int16_t lon, lat; };\nstruct CoastLine { uint16_t start, count; };\ninline constexpr CoastPoint coastPoints[] = {\n'
out+=''.join('{%d,%d},\n'%p for p in points)+'};\ninline constexpr CoastLine coastLines[] = {\n'
out+=''.join('{%d,%d},\n'%p for p in spans)+'};\n}\n'
Path('src/maps/WorldData.h').write_text(out)
Path('assets/maps/SOURCE.txt').write_text('Natural Earth 1:110m coastline. Public domain.\nhttps://www.naturalearthdata.com/about/terms-of-use/\nhttps://github.com/nvkelso/natural-earth-vector/blob/master/geojson/ne_110m_coastline.geojson\nSHA256 '+hashlib.sha256(source.read_bytes()).hexdigest()+'\nGenerated geometry: integer coordinates in 0.01 degrees; not for street navigation.\n')
print(len(points),'points;',len(spans),'lines;',len(points)*4+len(spans)*4,'bytes geometry')
